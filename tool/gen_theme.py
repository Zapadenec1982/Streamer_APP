#!/usr/bin/env python3
"""
gen_theme.py — the panel's Material 3 colour schemes as Dart: lib/theme/m3_schemes.g.dart.

The schemes live in one place, the THEMES table in the firmware's modules/ui_lvgl/src/ui_m3.cpp,
with the role order of struct Colors in ui_m3.h. The firmware's tools/ui/web_tokens.py already
reads that table for the web; this script imports its reader instead of parsing the table a
second time, and only writes Dart. MODESP_PLAYER_ROOT names the firmware checkout (default:
../modesp-player beside this repository).

    python3 tool/gen_theme.py           # rewrite lib/theme/m3_schemes.g.dart
    python3 tool/gen_theme.py --check   # exit 1 if it is out of date
"""

import os
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "lib" / "theme" / "m3_schemes.g.dart"


def firmware_root():
    fw = Path(os.environ.get("MODESP_PLAYER_ROOT", ROOT.parent / "modesp-player")).resolve()
    if not (fw / "tools" / "ui" / "web_tokens.py").is_file():
        raise SystemExit(f"no firmware checkout at {fw}: set MODESP_PLAYER_ROOT")
    return fw


def camel(name):
    head, *rest = name.split("_")
    return head + "".join(part.capitalize() for part in rest)


def render():
    sys.dont_write_bytecode = True  # leave no __pycache__ in the firmware's tree
    sys.path.insert(0, str(firmware_root() / "tools" / "ui"))
    import web_tokens  # the firmware's own reader of ui_m3.h / ui_m3.cpp

    roles = web_tokens.roles(web_tokens.HEADER.read_text(encoding="utf-8"))
    schemes = web_tokens.schemes(web_tokens.TABLE.read_text(encoding="utf-8"), len(roles))
    fields = [camel(r) for r in roles]
    lines = [
        "// GENERATED by tool/gen_theme.py from the firmware's modules/ui_lvgl/src/ui_m3.cpp.",
        "// Do not edit: change the table there and run the script again.",
        "",
        "import 'dart:ui';",
        "",
        "/// The panel's colour roles, in the order of struct Colors in ui_m3.h.",
        "class PanelColors {",
        "  const PanelColors({" + ", ".join(f"required this.{f}" for f in fields) + "});",
        "",
    ]
    lines += [f"  final Color {f};" for f in fields]
    lines += [
        "}",
        "",
        "/// One of the panel's schemes; [id] is its name in ui_m3.cpp.",
        "class PanelScheme {",
        "  const PanelScheme(this.id, this.colors);",
        "",
        "  final String id;",
        "  final PanelColors colors;",
        "}",
        "",
        "/// The panel's schemes, indexed by `ui.theme` — the panel's own setting picks one.",
        "const List<PanelScheme> panelSchemes = [",
    ]
    for name, values in schemes:
        args = ", ".join(f"{f}: Color(0xFF{v:06X})" for f, v in zip(fields, values))
        lines.append(f"  PanelScheme('{name}', PanelColors({args})),")
    lines += ["];", ""]
    return "\n".join(lines)


def formatted(text):
    """The text as `dart format` leaves it, so --check agrees with the formatter."""
    with tempfile.TemporaryDirectory() as tmp:
        path = Path(tmp) / OUT.name
        path.write_text(text, encoding="utf-8")
        subprocess.run(["dart", "format", "--output=write", str(path)], check=True,
                       stdout=subprocess.DEVNULL)
        return path.read_text(encoding="utf-8")


def main(argv):
    text = formatted(render())
    if "--check" in argv:
        current = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
        if current != text:
            print(f"{OUT.relative_to(ROOT)} is out of date: run python3 tool/gen_theme.py")
            return 1
        return 0
    OUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
